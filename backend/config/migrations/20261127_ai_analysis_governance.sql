CREATE TABLE IF NOT EXISTS public.ai_analysis_cache (
    cache_key TEXT PRIMARY KEY,
    owner_id UUID NOT NULL,
    feature TEXT NOT NULL,
    model TEXT NOT NULL,
    source_hash TEXT NOT NULL,
    response_json JSONB NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ai_analysis_cache_key_length CHECK (length(cache_key) = 64),
    CONSTRAINT ai_analysis_cache_source_hash_length CHECK (length(source_hash) = 64)
);

CREATE INDEX IF NOT EXISTS idx_ai_analysis_cache_expiration
    ON public.ai_analysis_cache (expires_at);
CREATE INDEX IF NOT EXISTS idx_ai_analysis_cache_owner_feature
    ON public.ai_analysis_cache (owner_id, feature, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.ai_analysis_locks (
    cache_key TEXT PRIMARY KEY,
    lock_token UUID NOT NULL,
    lease_until TIMESTAMPTZ NOT NULL,
    CONSTRAINT ai_analysis_locks_key_length CHECK (length(cache_key) = 64)
);

CREATE TABLE IF NOT EXISTS public.gemini_api_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    model TEXT NOT NULL,
    feature TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'started',
    provider_status INTEGER,
    error_category TEXT,
    duration_ms INTEGER,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT gemini_api_usage_status CHECK (status IN ('started', 'success', 'failed'))
);

CREATE INDEX IF NOT EXISTS idx_gemini_api_usage_model_started
    ON public.gemini_api_usage (model, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_gemini_api_usage_feature_started
    ON public.gemini_api_usage (feature, started_at DESC);

CREATE OR REPLACE FUNCTION public.claim_ai_analysis_lock(
    p_cache_key TEXT,
    p_lock_token UUID,
    p_lease_seconds INTEGER
) RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    rows_affected INTEGER := 0;
BEGIN
    IF p_lease_seconds < 1 OR p_lease_seconds > 600 THEN
        RAISE EXCEPTION 'lease duration out of range';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended(p_cache_key, 0));
    INSERT INTO public.ai_analysis_locks (cache_key, lock_token, lease_until)
    VALUES (p_cache_key, p_lock_token, NOW() + make_interval(secs => p_lease_seconds))
    ON CONFLICT (cache_key) DO UPDATE
       SET lock_token = EXCLUDED.lock_token,
           lease_until = EXCLUDED.lease_until
     WHERE public.ai_analysis_locks.lease_until <= NOW();
    GET DIAGNOSTICS rows_affected = ROW_COUNT;
    RETURN rows_affected > 0;
END;
$$;

CREATE OR REPLACE FUNCTION public.release_ai_analysis_lock(
    p_cache_key TEXT,
    p_lock_token UUID
) RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    rows_affected INTEGER := 0;
BEGIN
    DELETE FROM public.ai_analysis_locks
     WHERE cache_key = p_cache_key AND lock_token = p_lock_token;
    GET DIAGNOSTICS rows_affected = ROW_COUNT;
    RETURN rows_affected > 0;
END;
$$;

CREATE OR REPLACE FUNCTION public.reserve_gemini_api_request(
    p_model TEXT,
    p_feature TEXT,
    p_rpm_limit INTEGER,
    p_daily_limit INTEGER,
    p_request_id UUID
) RETURNS TABLE (
    allowed BOOLEAN,
    usage_id BIGINT,
    error_category TEXT,
    retry_after_seconds INTEGER,
    minute_count BIGINT,
    daily_count BIGINT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    request_now TIMESTAMPTZ := NOW();
    recent_minute BIGINT;
    recent_day BIGINT;
    inserted_id BIGINT;
    next_reset TIMESTAMPTZ;
BEGIN
    IF p_rpm_limit < 1 OR p_daily_limit < 1 THEN
        RETURN QUERY SELECT FALSE, NULL::BIGINT, 'budget_unavailable', NULL::INTEGER, 0::BIGINT, 0::BIGINT;
        RETURN;
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended('gemini:' || p_model, 0));
    SELECT COUNT(*) INTO recent_minute
      FROM public.gemini_api_usage
     WHERE model = p_model AND started_at > request_now - INTERVAL '1 minute';
    SELECT COUNT(*) INTO recent_day
      FROM public.gemini_api_usage
     WHERE model = p_model AND started_at > request_now - INTERVAL '24 hours';

    IF recent_day >= p_daily_limit THEN
        SELECT MIN(started_at) + INTERVAL '24 hours' INTO next_reset
          FROM public.gemini_api_usage
         WHERE model = p_model AND started_at > request_now - INTERVAL '24 hours';
        RETURN QUERY SELECT FALSE, NULL::BIGINT, 'quota_daily',
            GREATEST(1, CEIL(EXTRACT(EPOCH FROM (next_reset - request_now)))::INTEGER), recent_minute, recent_day;
        RETURN;
    END IF;
    IF recent_minute >= p_rpm_limit THEN
        SELECT MIN(started_at) + INTERVAL '1 minute' INTO next_reset
          FROM public.gemini_api_usage
         WHERE model = p_model AND started_at > request_now - INTERVAL '1 minute';
        RETURN QUERY SELECT FALSE, NULL::BIGINT, 'quota_rpm',
            GREATEST(1, CEIL(EXTRACT(EPOCH FROM (next_reset - request_now)))::INTEGER), recent_minute, recent_day;
        RETURN;
    END IF;

    INSERT INTO public.gemini_api_usage (request_id, model, feature, status, started_at)
    VALUES (p_request_id, p_model, p_feature, 'started', request_now)
    RETURNING id INTO inserted_id;
    RETURN QUERY SELECT TRUE, inserted_id, NULL::TEXT, NULL::INTEGER, recent_minute + 1, recent_day + 1;
END;
$$;

