// Bag weight constant (kg per bag)
export const BAG_WEIGHT_KG = 50;

/**
 * Get feed program entry for a specific week
 * @param {number} week - Week number (1-26)
 * @returns {Object|null} Feed program entry or null if invalid week
 */
export function getFeedProgramByWeek(week) {
  const clampedWeek = Math.max(1, Math.min(26, Math.floor(week)));
  return FEED_PROGRAM.find(entry => entry.week === clampedWeek) || null;
}

/**
 * Get feed program entry for a batch based on its age
 * @param {number} weeksSinceAcquired - Number of weeks since batch was acquired
 * @returns {Object} Feed program entry with calculated totals for the batch
 */
export function getFeedTargetForBatch(weeksSinceAcquired, pigCount) {
  const week = Math.max(1, Math.min(26, Math.floor(weeksSinceAcquired) + 1));
  const program = getFeedProgramByWeek(week);
  
  if (!program) {
    return null;
  }

  const totalWeeklyKg = program.weeklyFC * pigCount;
  const totalDailyKg = program.dailyFC * pigCount;
  const bagsNeeded = Math.ceil(totalWeeklyKg / BAG_WEIGHT_KG);
  const estimatedCost = program.referencePrice > 0 
    ? program.referencePrice * bagsNeeded 
    : null;

  return {
    week,
    ration: program.ration,
    phase: program.phase,
    dailyPerPigKg: program.dailyFC,
    weeklyPerPigKg: program.weeklyFC,
    totalDailyKg: Math.round(totalDailyKg * 100) / 100,
    totalWeeklyKg: Math.round(totalWeeklyKg * 100) / 100,
    bagsNeeded,
    estimatedCostPerBag: program.referencePrice > 0 ? Math.round(program.referencePrice * 100) / 100 : null,
    estimatedWeeklyCost: estimatedCost ? Math.round(estimatedCost * 100) / 100 : null
  };
}

/**
 * Get feed cost forecast for a batch for the next N weeks
 * @param {Object} batch - Batch object with pig_count, date_acquired
 * @param {Array} feedStocks - Array of feed stock objects with feed_type and unit_price
 * @param {number} forecastWeeks - Number of weeks to forecast (default 4)
 * @returns {Object} Cost forecast breakdown
 */
export function getFeedCostForecast(batch, feedStocks, forecastWeeks = 4) {
  const pigCount = batch.pig_count || 0;
  if (pigCount === 0) {
    return { error: 'No pigs in batch' };
  }

  const acquiredDate = new Date(batch.date_acquired);
  const now = new Date();
  const weeksSinceAcquired = Math.floor((now - acquiredDate) / (1000 * 60 * 60 * 24 * 7));
  const currentWeek = Math.max(1, Math.min(26, weeksSinceAcquired + 1));

  const forecast = [];
  let totalProjectedKg = 0;
  let totalProjectedCost = 0;

  for (let i = 0; i < forecastWeeks; i++) {
    const week = Math.min(26, currentWeek + i);
    const program = getFeedProgramByWeek(week);
    
    if (!program) break;

    const weeklyKgPerPig = program.weeklyFC;
    const totalWeeklyKg = weeklyKgPerPig * pigCount;
    const bagsNeeded = Math.ceil(totalWeeklyKg / BAG_WEIGHT_KG);

    // Find matching feed stock price
    const stock = feedStocks.find(s => 
      s.feed_type.toLowerCase() === program.ration.toLowerCase() ||
      s.feed_type.toLowerCase().includes(program.ration.toLowerCase().split('-')[0]) ||
      program.ration.toLowerCase().includes(s.feed_type.toLowerCase().split(' ')[0])
    );

    const unitPrice = stock?.unit_price || program.referencePrice || 0;
    const weeklyCost = bagsNeeded * unitPrice;

    forecast.push({
      week,
      ration: program.ration,
      phase: program.phase,
      weeklyKgPerPig,
      totalWeeklyKg: Math.round(totalWeeklyKg * 100) / 100,
      bagsNeeded,
      unitPrice: Math.round(unitPrice * 100) / 100,
      weeklyCost: Math.round(weeklyCost * 100) / 100
    });

    totalProjectedKg += totalWeeklyKg;
    totalProjectedCost += weeklyCost;
  }

  // Group by ration type
  const byRation = {};
  forecast.forEach(entry => {
    if (!byRation[entry.ration]) {
      byRation[entry.ration] = {
        ration: entry.ration,
        phase: entry.phase,
        totalKg: 0,
        totalBags: 0,
        totalCost: 0,
        avgUnitPrice: 0
      };
    }
    byRation[entry.ration].totalKg += entry.totalWeeklyKg;
    byRation[entry.ration].totalBags += entry.bagsNeeded;
    byRation[entry.ration].totalCost += entry.weeklyCost;
  });

  Object.values(byRation).forEach(entry => {
    entry.avgUnitPrice = entry.totalBags > 0 
      ? Math.round((entry.totalCost / entry.totalBags) * 100) / 100 
      : 0;
    entry.totalKg = Math.round(entry.totalKg * 100) / 100;
    entry.totalCost = Math.round(entry.totalCost * 100) / 100;
  });

  return {
    batchId: batch.id,
    currentWeek,
    forecastWeeks,
    pigCount,
    forecast,
    summary: {
      totalProjectedKg: Math.round(totalProjectedKg * 100) / 100,
      totalProjectedCost: Math.round(totalProjectedCost * 100) / 100,
      byRation: Object.values(byRation)
    }
  };
}

