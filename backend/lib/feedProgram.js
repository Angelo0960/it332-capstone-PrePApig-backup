/**
 * Calculate actual vs planned feed consumption for a batch
 * @param {Object} batch - Batch object
 * @param {Array} feedRecords - Actual feed records for the batch
 * @param {number} weeksToAnalyze - Number of past weeks to analyze
 * @returns {Object} Comparison of actual vs planned
 */
export function getActualVsPlanned(batch, feedRecords, weeksToAnalyze = 4) {
  const pigCount = batch.pig_count || 0;
  if (pigCount === 0) {
    return { error: 'No pigs in batch' };
  }

  const acquiredDate = new Date(batch.date_acquired);
  const now = new Date();
  const weeksSinceAcquired = Math.floor((now - acquiredDate) / (1000 * 60 * 60 * 24 * 7));
  const currentWeek = Math.max(1, Math.min(26, weeksSinceAcquired + 1));

  const comparison = [];
  let totalActualKg = 0;
  let totalPlannedKg = 0;

  for (let i = 0; i < weeksToAnalyze; i++) {
    const week = Math.max(1, currentWeek - i);
    const program = getFeedProgramByWeek(week);
    
    if (!program) continue;

    const plannedWeeklyKg = program.weeklyFC * pigCount;
    
    // Calculate actual feed for this week
    const weekStart = new Date(acquiredDate.getTime() + (week - 1) * 7 * 24 * 60 * 60 * 1000);
    const weekEnd = new Date(weekStart.getTime() + 7 * 24 * 60 * 60 * 1000);
    
    const actualWeeklyKg = feedRecords
      .filter(r => {
        const recordDate = new Date(r.feeding_date);
        return recordDate >= weekStart && recordDate < weekEnd;
      })
      .reduce((sum, r) => sum + Number(r.quantity_kg || 0), 0);

    const variance = actualWeeklyKg - plannedWeeklyKg;
    const variancePercent = plannedWeeklyKg > 0 
      ? Math.round((variance / plannedWeeklyKg) * 10000) / 100 
      : 0;

    comparison.push({
      week,
      ration: program.ration,
      phase: program.phase,
      plannedKg: Math.round(plannedWeeklyKg * 100) / 100,
      actualKg: Math.round(actualWeeklyKg * 100) / 100,
      varianceKg: Math.round(variance * 100) / 100,
      variancePercent
    });

    totalPlannedKg += plannedWeeklyKg;
    totalActualKg += actualWeeklyKg;
  }

  return {
    batchId: batch.id,
    currentWeek,
    comparison: comparison.reverse(), // Oldest first
    summary: {
      totalPlannedKg: Math.round(totalPlannedKg * 100) / 100,
      totalActualKg: Math.round(totalActualKg * 100) / 100,
      totalVarianceKg: Math.round((totalActualKg - totalPlannedKg) * 100) / 100,
      totalVariancePercent: totalPlannedKg > 0 
        ? Math.round(((totalActualKg - totalPlannedKg) / totalPlannedKg) * 10000) / 100 
        : 0
    }
  };
}

